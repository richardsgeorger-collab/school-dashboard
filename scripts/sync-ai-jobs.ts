// Writes the AI job registry (src/ai/jobs.ts: each job's own instructions and tool, and its size caps) to
// supabase/functions/_shared/aiJobs.ts (a module, so the function's bundle carries it), where the AI function builds
// every call from it. Run by `npm run build`;
// src/ai/jobs.test.ts fails when the file is out of date.
//   npx tsx scripts/sync-ai-jobs.ts
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { JOBS } from '../src/ai/jobs';

const out = join(import.meta.dirname, '..', 'supabase', 'functions', '_shared', 'aiJobs.ts');
writeFileSync(out, `// GENERATED by scripts/sync-ai-jobs.ts from src/ai/jobs.ts. Do not edit here.\nimport type { Job } from './jobRules.ts';\n\nexport const JOBS: Record<string, Job> = ${JSON.stringify(JOBS, null, 1)};\n`);
console.log(`wrote ${Object.keys(JOBS).length} AI jobs to supabase/functions/_shared/aiJobs.ts`);
